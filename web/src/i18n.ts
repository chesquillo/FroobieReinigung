export const LANGUAGES = [
  { code: 'de', label: 'Deutsch', flag: '🇩🇪' },
  { code: 'en', label: 'English', flag: '🇬🇧' },
  { code: 'es', label: 'Español', flag: '🇪🇸' },
] as const;

function initialLang() {
  try {
    const saved = localStorage.getItem('froobie_lang');
    if (saved && ['de', 'en', 'es'].includes(saved)) return saved;
  } catch {
    /* sin almacenamiento */
  }
  const nav = navigator.language.slice(0, 2);
  return ['de', 'en', 'es'].includes(nav) ? nav : 'de';
}

i18n.use(initReactI18next).init({
  resources: { de: { translation: de }, en: { translation: en }, es: { translation: es } },
  lng: initialLang(),
  fallbackLng: 'de',
  interpolation: { escapeValue: false },
});

i18n.on('languageChanged', (lng) => {
  document.documentElement.lang = lng;
  try {
    localStorage.setItem('froobie_lang', lng);
  } catch {
    /* ignorar */
  }
});

export function weekdayNames(lang: string, style: 'short' | 'long' = 'short') {
  const locale = lang === 'de' ? 'de-DE' : lang === 'es' ? 'es-ES' : 'en-GB';
  // 2024-01-01 fue lunes
  return [1, 2, 3, 4, 5, 6, 7].map((d) =>
    new Intl.DateTimeFormat(locale, { weekday: style, timeZone: 'UTC' }).format(new Date(Date.UTC(2024, 0, d))),
  );
}

export function formatDate(date: string | Date, lang: string) {
  const locale = lang === 'de' ? 'de-DE' : lang === 'es' ? 'es-ES' : 'en-GB';
  const d = typeof date === 'string' && date.length === 10 ? new Date(date + 'T12:00:00') : new Date(date);
  return new Intl.DateTimeFormat(locale, { weekday: 'short', day: '2-digit', month: '2-digit', year: 'numeric' }).format(d);
}

export function formatDateTime(date: string | Date, lang: string) {
  const locale = lang === 'de' ? 'de-DE' : lang === 'es' ? 'es-ES' : 'en-GB';
  return new Intl.DateTimeFormat(locale, { dateStyle: 'short', timeStyle: 'short' }).format(new Date(date));
}

export default i18n;
